function setLanguage(lang) {
  if (!ASSURA_I18N[lang]) lang = 'en';
  
  try {
    localStorage.setItem('assura_lang', lang);
  } catch (e) {}

  const langAttrMap = { en: 'en', zh: 'zh-CN', bm: 'ms', ta: 'ta' };
  document.documentElement.lang = langAttrMap[lang] || 'en';

  document.querySelectorAll('.lang-btn').forEach(btn => {
    const bLang = btn.getAttribute('data-lang') || (btn.textContent.toLowerCase().includes('zh') || btn.textContent.includes('中文') ? 'zh' : (btn.textContent.toLowerCase().includes('bm') ? 'bm' : (btn.textContent.includes('தமிழ்') || btn.textContent.toLowerCase().includes('ta') ? 'ta' : 'en')));
    if (bLang === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  const dict = ASSURA_I18N[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  applyAutomaticPageTranslations(lang, dict);

  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, dict } }));
}

function applyAutomaticPageTranslations(lang, dict) {
  const navMap = {
    'home': dict.nav_home,
    'about us': dict.nav_about,
    'services': dict.nav_services,
    'media': dict.nav_media,
    'announcements': dict.nav_announcements,
    'download apps': dict.nav_download,
    'download app': dict.nav_download,
    'clinical portal': dict.nav_portal
  };

  document.querySelectorAll('.nav-link, .footer-links a').forEach(a => {
    const txt = a.textContent.trim().toLowerCase();
    if (navMap[txt]) {
      a.textContent = navMap[txt];
    }
  });

  document.querySelectorAll('.portal-pill, .portal-pill-patient').forEach(pill => {
    const span = pill.querySelector('span');
    if (span) {
      span.textContent = dict.nav_portal;
    }
  });
}

function getCurrentLanguage() {
  try {
    const saved = localStorage.getItem('assura_lang');
    if (saved && ASSURA_I18N[saved]) return saved;
  } catch (e) {}
  
  const navLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  if (navLang.startsWith('zh')) return 'zh';
  if (navLang.startsWith('ms') || navLang.startsWith('id')) return 'bm';
  if (navLang.startsWith('ta')) return 'ta';
  return 'en';
}

window.setLanguage = setLanguage;
window.setSubPageLang = setLanguage;
window.getCurrentLanguage = getCurrentLanguage;
window.ASSURA_I18N = ASSURA_I18N;

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    setLanguage(getCurrentLanguage());
  });
} else {
  setLanguage(getCurrentLanguage());
}
